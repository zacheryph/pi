import { readFileSync, realpathSync, statSync } from "node:fs";
import { dirname, isAbsolute, join, parse, relative, resolve, sep } from "node:path";
import { userInfo } from "node:os";
import { parseDocument } from "yaml";
import type { SandboxRuntimeConfig } from "@anthropic-ai/sandbox-runtime";

export interface Policy {
  version: 1;
  sandbox: SandboxRuntimeConfig;
  env: { pass: string[]; set: Record<string, string> };
}

export class PolicyError extends Error {
  constructor(path: string, field: string, reason: string) {
    super(`${path}: ${field}: ${reason}`);
  }
}

export const policyPath = () => join(userInfo().homedir, ".pi/agent/isolation.yaml");
const envName = /^[A-Za-z_][A-Za-z0-9_]*$/;
// These affect host loaders, shell startup, helpers, or SRT's proxy setup.
const reserved =
  /^(?:HOME|PATH|TMPDIR|TMP|TEMP|ENV|BASH_ENV|SHELLOPTS|BASHOPTS|CDPATH|GLOBIGNORE|IFS|ZDOTDIR|NODE_.*|JITI_.*|RIPGREP_.*|RG_.*|OPENSSL_.*|LD_.*|DYLD_.*|BASH_FUNC_.*|SRT_.*|SANDBOX_.*|CLAUDE_.*|.*_PROXY|.*_proxy|JAVA_.*|JDK_.*|_JAVA_OPTIONS|PYTHON.*|PERL.*|RUBY.*|GIT_CONFIG.*|SSL_CERT_.*|CURL_CA_BUNDLE)$/;

export function loadPolicy(path: string): Policy {
  const fail = (field: string, reason = "invalid value"): never => {
    throw new PolicyError(path, field, reason);
  };
  let raw: unknown;
  try {
    const doc = parseDocument(readFileSync(path, "utf8"), { uniqueKeys: true });
    if (doc.errors.length) fail("document", "invalid YAML");
    raw = doc.toJS({ maxAliasCount: 0 });
  } catch (error) {
    if (error instanceof PolicyError) throw error;
    fail("document", "cannot read or parse policy");
  }
  function object(value: unknown, field: string, keys?: string[]): Record<string, unknown> {
    if (!value || typeof value !== "object" || Array.isArray(value)) fail(field);
    const record = value as Record<string, unknown>;
    if (keys && Object.keys(record).some((key) => !keys.includes(key))) {
      // Do not echo arbitrary YAML keys: even a key may contain a credential.
      fail(field, "unknown key");
    }
    return record;
  }
  function strings(value: unknown, field: string): string[] {
    if (!Array.isArray(value) || value.some((v) => typeof v !== "string" || !v || v.includes("\0")))
      fail(field);
    return value as string[];
  }
  const root = object(raw, "document", ["version", "sandbox", "env"]);
  if (root.version !== 1) fail("version", "expected 1");
  const sandbox = object(root.sandbox, "sandbox", ["network", "filesystem", "allowPty"]);
  const network = object(sandbox.network, "sandbox.network", ["allowedDomains", "deniedDomains"]);
  const fs = object(sandbox.filesystem, "sandbox.filesystem", [
    "denyRead",
    "allowWrite",
    "denyWrite",
  ]);
  for (const key of ["allowedDomains", "deniedDomains"])
    strings(network[key], `sandbox.network.${key}`);
  for (const key of ["denyRead", "allowWrite", "denyWrite"]) {
    const paths = strings(fs[key], `sandbox.filesystem.${key}`);
    // Literal paths only: globs and Linux expansion cannot prove installation protection.
    if (paths.some((p) => /[*?[\]{}\n\r]/.test(p) || (p.startsWith("~") && !p.startsWith("~/"))))
      fail(`sandbox.filesystem.${key}`, "expected literal paths");
  }
  if (sandbox.allowPty !== undefined && typeof sandbox.allowPty !== "boolean")
    fail("sandbox.allowPty");
  const env = object(root.env ?? {}, "env", ["pass", "set"]);
  const pass = strings(env.pass ?? [], "env.pass");
  const set = object(env.set ?? {}, "env.set");
  for (const name of [...pass, ...Object.keys(set)]) {
    if (!envName.test(name) || reserved.test(name))
      fail("env", "invalid or reserved variable name");
  }
  if (Object.values(set).some((v) => typeof v !== "string" || v.includes("\0")))
    fail("env.set", "expected literal strings");
  return {
    version: 1,
    sandbox: sandbox as unknown as SandboxRuntimeConfig,
    env: { pass, set: set as Record<string, string> },
  };
}

/** Resolve the existing prefix, including symlinks, without requiring the final path to exist. */
export function canonical(path: string): string {
  try {
    return realpathSync(path);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    const parent = dirname(path);
    if (parent === path) throw error;
    return join(canonical(parent), relative(parent, path));
  }
}

export function contains(parent: string, child: string): boolean {
  const rel = relative(parent, child);
  return rel === "" || (!rel.startsWith(`..${sep}`) && rel !== ".." && !isAbsolute(rel));
}

/**
 * Refuse grants that could let the session replace a protected object.
 *
 * A writable ancestor normally permits unlink/rename of a protected child even
 * when the child is in denyWrite. macOS Seatbelt profiles generated by SRT
 * close that hole: every denyWrite path and its ancestor directories get
 * `deny file-write-unlink`/`file-write-create` after the allow rules, so a broad
 * grant such as `~/.pi/agent` is safe there. Other platforms keep the strict
 * layout rule until the same protection is verified. A grant inside a protected
 * object is always refused: the deny would silently override it.
 */
export function preparePolicy(
  policy: Policy,
  path: string,
  cwd: string,
  protectedPaths: string[],
  home = userInfo().homedir,
  platform: NodeJS.Platform = process.platform,
): SandboxRuntimeConfig {
  const expand = (p: string) => resolve(cwd, p.startsWith("~/") ? join(home, p.slice(2)) : p);
  const fs = policy.sandbox.filesystem;
  const allowWrite = fs.allowWrite.map((entry) => {
    const p = expand(entry as string);
    const resolved = canonical(p);
    // A symlinked write root can be retargeted outside the inspected grant.
    if (resolved !== p && canonical(dirname(p)) !== dirname(resolved))
      throw new PolicyError(path, "sandbox.filesystem.allowWrite", "unsafe symlinked write root");
    return resolved;
  });
  const protectedObjects = [path, ...protectedPaths].flatMap((p) => [
    resolve(p),
    canonical(resolve(p)),
  ]);
  for (const grant of allowWrite) {
    if (grant === parse(grant).root)
      throw new PolicyError(
        path,
        "sandbox.filesystem.allowWrite",
        "refusing a filesystem-root grant",
      );
    for (const target of protectedObjects) {
      const ancestorGrant = contains(grant, target) || contains(grant, dirname(target));
      // Where the OS sandbox blocks moves of denied paths, only the inside case is wrong.
      if (contains(target, grant) || (platform !== "darwin" && ancestorGrant)) {
        throw new PolicyError(
          path,
          "sandbox.filesystem.allowWrite",
          "grant overlaps policy or trusted installation; use a separate project directory",
        );
      }
    }
  }
  const info = statSync(path);
  if (!info.isFile() || (info.mode & 0o022) !== 0 || info.uid !== process.getuid?.()) {
    throw new PolicyError(
      path,
      "document",
      "policy must be user-owned and not writable by group or others",
    );
  }
  return {
    ...policy.sandbox,
    network: { ...policy.sandbox.network, strictAllowlist: true },
    filesystem: {
      denyRead: fs.denyRead.map((p) => canonical(expand(p as string))),
      allowWrite,
      denyWrite: [...fs.denyWrite.map((p) => canonical(expand(p as string))), ...protectedObjects],
    },
  };
}

export function childEnvironment(
  policy: Policy,
  host: NodeJS.ProcessEnv,
  node: string,
  home = userInfo().homedir,
): NodeJS.ProcessEnv {
  const env: NodeJS.ProcessEnv = {
    HOME: home,
    PATH: [
      ...new Set([
        dirname(node),
        "/opt/homebrew/bin",
        "/usr/local/bin",
        "/usr/bin",
        "/bin",
        "/usr/sbin",
        "/sbin",
      ]),
    ].join(":"),
    TMPDIR: "/tmp",
  };
  for (const key of policy.env.pass) if (host[key] !== undefined) env[key] = host[key];
  return Object.assign(env, policy.env.set);
}
